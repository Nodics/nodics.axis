import { webcrypto } from 'node:crypto';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import {
  createProcessTriggerCommandIntent,
  executeProcessTriggerCommand,
  inspectProcessTriggerCommandReceipt,
} from '../../../src/operations/processWorkflow/api/processTriggerCommandClient';

const connection = {
  moduleName: 'workflow',
  instanceId: 'workflow',
  endpoint: 'http://workflow.example/nodics/process',
  environment: 'local',
  state: 'UP' as const,
};
const configuration = {
  accessToken: 'synthetic-token',
  enterpriseCode: 'default',
  timeoutMs: 1000,
};
const body = { status: 'DRAFT', definitionCode: 'review', code: 'review-job' };
// Fixed synthetic v1 projections independently generated by the native owner
// digest/project contract. Production Axis imports no backend source.
const completed = {
  contractVersion: 1,
  tenantCode: 'local',
  enterpriseCode: 'default',
  principalCode: 'operator',
  moduleName: 'workflow',
  operation: 'trigger.create',
  commandCode:
    'command-8fe4f078d1551ed38213a5c63e1aff9aee68f973d75bfede0c4712688b320c3a',
  argumentsDigest: '66156c4a4cb4b0c644e9908727b6f9878e790d6c2beb0891fed16af94f5c3451',
  state: 'COMPLETED',
  resultIdentity: 'review-job',
  resultDigest: '01e99f0eeac6d134651aead5d431e43d6943aff717ef40d6d24de278c1b406b6',
};
const executionBody = {
  version: 3,
  instanceCode: 'axis-trigger-fixture-instance',
  correlationId: 'fixture-correlation',
  context: { source: 'axis-trigger-console' },
};
const executionReceipt = {
  ...completed,
  operation: 'trigger.execute',
  commandCode:
    'command-56c0fab8e67eee6b309457056ae27a70ca6f881666368450f6f2621ec3286fc6',
  argumentsDigest: 'ff8252733689c37a9d78dc4bb621b83edf02d9f305007a45ba12a66561180a37',
  resultDigest: 'd5fb1ca37e675e0007862a4007383cd63a5831b57a79cad556c4631f2c813295',
};
const original = () =>
  Object.freeze({
    ...createProcessTriggerCommandIntent('create', 'review-job', body, 'ENABLED'),
    idempotencyKey: 'axis-trigger-test-key',
  });
const response = (data: unknown, code = 'SUC_PROCESS_00010') =>
  new Response(JSON.stringify({ code, data }), { status: 200 });
beforeEach(() => vi.stubGlobal('crypto', webcrypto));
afterEach(() => {
  vi.restoreAllMocks();
  vi.unstubAllGlobals();
});

describe('Native Process trigger commands and original receipts', () => {
  it('preserves unkeyed behavior when recording is explicitly disabled and sends only the exact command', async () => {
    const intent = createProcessTriggerCommandIntent(
      'create',
      'review-job',
      body,
      'DISABLED',
    );
    const fetcher = vi.spyOn(globalThis, 'fetch').mockResolvedValue(response(body));
    expect(
      await executeProcessTriggerCommand(connection, configuration, intent),
    ).toEqual({ triggerCode: 'review-job' });
    expect(intent.idempotencyKey).toBeUndefined();
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect((fetcher.mock.calls[0]?.[0] as URL).pathname).toBe(
      '/nodics/process/v0/triggers',
    );
    expect(fetcher.mock.calls[0]?.[1]).toMatchObject({
      method: 'POST',
      body: intent.bodyJson,
    });
    expect(fetcher.mock.calls[0]?.[1]?.headers).not.toHaveProperty('Idempotency-Key');
  });
  it('keeps one immutable original body/key per intent when recording is enabled', async () => {
    const input = { ...body };
    const intent = createProcessTriggerCommandIntent(
      'create',
      'review-job',
      input,
      'ENABLED',
    );
    const other = createProcessTriggerCommandIntent(
      'create',
      'review-job',
      input,
      'ENABLED',
    );
    input.status = 'ACTIVE';
    expect(intent.idempotencyKey).toMatch(/^axis-trigger-/);
    expect(intent.idempotencyKey).not.toBe(other.idempotencyKey);
    expect(JSON.parse(intent.bodyJson)).toEqual(body);
    const fetcher = vi.spyOn(globalThis, 'fetch').mockResolvedValue(response(body));
    await executeProcessTriggerCommand(connection, configuration, intent);
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(fetcher.mock.calls[0]?.[1]?.headers).toHaveProperty(
      'Idempotency-Key',
      intent.idempotencyKey,
    );
  });
  it('uses one native status-only PATCH with no invented schedule', async () => {
    const intent = createProcessTriggerCommandIntent(
      'update',
      'review-job',
      { status: 'ACTIVE' },
      'ENABLED',
    );
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockResolvedValue(response({ code: 'review-job', status: 'ACTIVE' }));
    await executeProcessTriggerCommand(connection, configuration, intent);
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(fetcher.mock.calls[0]?.[1]).toMatchObject({
      method: 'PATCH',
      body: '{"status":"ACTIVE"}',
    });
  });
  it('requires the exact archived identity and inactive state', async () => {
    const intent = createProcessTriggerCommandIntent(
      'archive',
      'review-job',
      {},
      'ENABLED',
    );
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockResolvedValue(
        response({ code: 'review-job', status: 'ARCHIVED', active: false }),
      );
    expect(
      await executeProcessTriggerCommand(connection, configuration, intent),
    ).toEqual({ triggerCode: 'review-job' });
    expect((fetcher.mock.calls[0]?.[0] as URL).pathname).toBe(
      '/nodics/process/v0/triggers/review-job/archive',
    );
  });
  it('accepts a trigger execution only for its acknowledged exact requested instance and version', async () => {
    const intent = createProcessTriggerCommandIntent(
      'execute',
      'review-job',
      executionBody,
      'ENABLED',
    );
    const fetcher = vi.spyOn(globalThis, 'fetch').mockResolvedValue(
      response(
        {
          trigger: { code: 'review-job', definitionCode: 'review' },
          execution: {
            instance: {
              code: executionBody.instanceCode,
              definitionCode: 'review',
              version: 3,
              startCompleted: true,
              status: 'WAITING',
            },
          },
        },
        'SUC_PROCESS_00011',
      ),
    );
    expect(
      await executeProcessTriggerCommand(connection, configuration, intent),
    ).toEqual({ triggerCode: 'review-job', instanceCode: executionBody.instanceCode });
    expect(fetcher).toHaveBeenCalledTimes(1);
  });
  it.each([
    { code: 'SUC_PROCESS_00010', data: { ...body, code: 'foreign' } },
    { code: 'SUC_PROCESS_00010', data: { code: 'review-job' } },
    { code: 'SUC_PROCESS_00010', data: { ...body, status: 'ACTIVE' } },
    { code: 'SUC_PROCESS_00010', data: { ...body, acknowledged: false } },
    { code: 'SUC_PROCESS_00010', data: body, result: body },
    { code: 'SUC_PROCESS_00010', data: body, success: false },
    { code: 'SUC_PROCESS_00000', data: body },
    { code: 'SUC_PROCESS_00010', data: { modifiedCount: 1 } },
  ])(
    'holds incompatible original acknowledgements as unconfirmed without replay',
    async (envelope) => {
      const fetcher = vi
        .spyOn(globalThis, 'fetch')
        .mockResolvedValue(new Response(JSON.stringify(envelope), { status: 200 }));
      await expect(
        executeProcessTriggerCommand(connection, configuration, original()),
      ).rejects.toThrow(/unconfirmed/);
      expect(fetcher).toHaveBeenCalledTimes(1);
    },
  );
  it('does not retry a lost native command response or inspect automatically', async () => {
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockRejectedValue(new TypeError('Response lost'));
    await expect(
      executeProcessTriggerCommand(connection, configuration, original()),
    ).rejects.toThrow(
      'The Process service could not be reached. Refresh its current evidence before trying again.',
    );
    expect(fetcher).toHaveBeenCalledTimes(1);
  });
  it('rejects incomplete or mismatched execution acknowledgement', async () => {
    const intent = createProcessTriggerCommandIntent(
      'execute',
      'review-job',
      executionBody,
      'ENABLED',
    );
    const fetcher = vi.spyOn(globalThis, 'fetch').mockResolvedValue(
      response(
        {
          trigger: { code: 'review-job', definitionCode: 'review' },
          execution: {
            instance: {
              code: 'other-instance',
              definitionCode: 'review',
              version: 2,
              status: 'WAITING',
            },
          },
        },
        'SUC_PROCESS_00011',
      ),
    );
    await expect(
      executeProcessTriggerCommand(connection, configuration, intent),
    ).rejects.toThrow(/unconfirmed/);
    expect(fetcher).toHaveBeenCalledTimes(1);
  });
  it('recovers only an exact owner-bound completed receipt through the read-only query', async () => {
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockResolvedValue(response(completed));
    expect(
      await inspectProcessTriggerCommandReceipt(
        connection,
        configuration,
        original(),
        'local',
      ),
    ).toEqual({ state: 'COMPLETED', triggerCode: 'review-job' });
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect((fetcher.mock.calls[0]?.[0] as URL).pathname).toBe(
      '/nodics/process/v0/triggers/review-job/commands/create/receipt/query',
    );
    expect(JSON.parse(fetcher.mock.calls[0]?.[1]?.body as string)).toEqual({
      command: body,
      idempotencyKey: 'axis-trigger-test-key',
    });
    expect(fetcher.mock.calls[0]?.[1]?.headers).not.toHaveProperty('Idempotency-Key');
  });
  it('keeps missing/started original evidence unknown without using current record state', async () => {
    const unknown = Object.fromEntries(
      Object.entries(completed).filter(
        ([key]) => !['resultIdentity', 'resultDigest'].includes(key),
      ),
    );
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockResolvedValue(response({ ...unknown, state: 'OUTCOME_UNKNOWN' }));
    expect(
      await inspectProcessTriggerCommandReceipt(
        connection,
        configuration,
        original(),
        'local',
      ),
    ).toEqual({ state: 'OUTCOME_UNKNOWN', triggerCode: 'review-job' });
    expect(fetcher).toHaveBeenCalledTimes(1);
  });
  it.each([
    { tenantCode: 'foreign' },
    { enterpriseCode: 'foreign' },
    { principalCode: 'foreign' },
    { moduleName: 'other' },
    { operation: 'trigger.execute' },
    { contractVersion: 2 },
    { commandCode: 'command-foreign' },
    { argumentsDigest: 'foreign' },
    { resultIdentity: 'foreign' },
    { resultDigest: 'foreign' },
    { retryToken: 'never-execute' },
  ])(
    'rejects foreign, corrupt or extended original receipt evidence without replay',
    async (changed) => {
      const fetcher = vi
        .spyOn(globalThis, 'fetch')
        .mockResolvedValue(response({ ...completed, ...changed }));
      await expect(
        inspectProcessTriggerCommandReceipt(
          connection,
          configuration,
          original(),
          'local',
        ),
      ).rejects.toThrow(/unconfirmed/);
      expect(fetcher).toHaveBeenCalledTimes(1);
      expect((fetcher.mock.calls[0]?.[0] as URL).pathname).toContain('/receipt/query');
    },
  );
  it('uses the original requested instance after a completed execution receipt without starting another workflow', async () => {
    const intent = Object.freeze({
      ...createProcessTriggerCommandIntent(
        'execute',
        'review-job',
        executionBody,
        'ENABLED',
      ),
      idempotencyKey: 'axis-trigger-test-key',
    });
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockResolvedValue(response(executionReceipt));
    expect(
      await inspectProcessTriggerCommandReceipt(
        connection,
        configuration,
        intent,
        'local',
      ),
    ).toEqual({
      state: 'COMPLETED',
      triggerCode: 'review-job',
      instanceCode: executionBody.instanceCode,
    });
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect((fetcher.mock.calls[0]?.[0] as URL).pathname).toContain(
      '/commands/execute/receipt/query',
    );
  });
  it('does not send an inspection request for an unrecorded intent', async () => {
    const fetcher = vi.spyOn(globalThis, 'fetch');
    const intent = createProcessTriggerCommandIntent(
      'create',
      'review-job',
      body,
      'DISABLED',
    );
    await expect(
      inspectProcessTriggerCommandReceipt(connection, configuration, intent, 'local'),
    ).rejects.toThrow(/not enabled/);
    expect(fetcher).not.toHaveBeenCalled();
  });
  it('keeps a denied receipt lookup separate from mutation replay', async () => {
    const fetcher = vi
      .spyOn(globalThis, 'fetch')
      .mockResolvedValue(
        new Response(JSON.stringify({ message: 'Not permitted' }), { status: 403 }),
      );
    await expect(
      inspectProcessTriggerCommandReceipt(
        connection,
        configuration,
        original(),
        'local',
      ),
    ).rejects.toThrow('Not permitted');
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect((fetcher.mock.calls[0]?.[0] as URL).pathname).toContain('/receipt/query');
  });
});
